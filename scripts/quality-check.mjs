import fs from 'node:fs';
import assert from 'node:assert/strict';
import postcss from 'postcss';
const read = path => fs.readFileSync(new URL('../'+path, import.meta.url),'utf8');
const css = read('src/yoru-atelier.css');
const app = read('src/GodApp.jsx');
const main = read('src/main.jsx');
const backup = read('src/dataBackup.js');
const sw = read('public/sw.js');
const ast=postcss.parse(css,{from:'src/yoru-atelier.css'});
let declarations=0,important=0;
ast.walkDecls(d=>{declarations++;if(d.important)important++;});
assert(css.length < 67000,'CSS grew beyond the YORU budget');
assert.equal((css.match(/@import /g)||[]).length,1,'Expected a single font import');
assert(!main.includes("import './yoru-nightshift.css'"),'Legacy styles still loaded');
assert(!main.includes("import './established-yoru.css'"),'Legacy styles still loaded');
assert(main.includes("import './yoru-atelier.css'"),'Canonical stylesheet not loaded');
assert(!app.includes('className="g-fab"'),'Floating expense button obstructs navigation');
assert(app.includes('const budgetRemaining = budgetTotal - totalExpense'),'Exceeded budgets would be hidden');
assert(app.includes('onChange(category, event.target.value)'),'Budget editor disconnected');
assert(app.includes('onMarkLoan(row)')&&app.includes('onUndoLoan(row)'),'Loan handlers missing');
assert(app.includes("onLaunchSettings={() => launch('.product-settings-button')}"),'Settings action missing');
assert(backup.includes('existingEntries')&&backup.includes('rollbackError'),'Backup transaction protection missing');
assert(sw.includes('cache.put(path, response)'),'Offline assets are not precached');
assert(important < 200,'Important-rule count too high');
assert(!read('src/ProductCenter.jsx').includes("import { jsPDF } from 'jspdf'"),'PDF engine must lazy-load');
console.log(JSON.stringify({result:'pass',cssBytes:Buffer.byteLength(css),declarations,important},null,2));
